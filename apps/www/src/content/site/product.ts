export const productContentByLocale: DeepReadonly<Record<Locale, ProductContent>> = deepFreeze({
	en: pageEn,
	zh: pageZh,
});

export function getProductContent(locale: Locale): DeepReadonly<ProductContent> {
	return productContentByLocale[locale];
}
