import type { PageMeta } from "./global";
import { type DeepReadonly, deepFreeze, type FactualClaim, type Locale } from "./types";

export type ProductWorkbenchViewId = "scope" | "answer" | "sources" | "next-test";
export type ProductActivityId = "define-scope" | "observe-answer" | "inspect-evidence" | "choose-next-test";
export type ProductClaim = FactualClaim & { limitation: string };

export interface ProductWorkbenchUi {
	tabListLabel: string;
	capabilityContextLabel: string;
	illustrativeLabel: string;
	knownLabel: string;
	unknownLabel: string;
	currentSoftwareLabel: string;
	managedDeliveryLabel: string;
	verifiedEvidenceLabel: string;
	directionLabel: string;
}

export type ProductWorkbenchField =
	| { label: string; state: "known"; value: string }
	| { label: string; state: "unknown"; reason: string };

export interface ProductWorkbenchView {
	id: ProductWorkbenchViewId;
	tabLabel: string;
	title: string;
	description: string;
	status: "illustrative";
	claims: readonly ProductClaim[];
	fields: readonly ProductWorkbenchField[];
}

export interface ProductActivity {
	id: ProductActivityId;
	title: string;
	summary: string;
	claims: readonly ProductClaim[];
}

export interface ProductHomePreview {
	title: string;
	summary: string;
	evidenceLabel: string;
	limitation: string;
	claims: readonly ProductClaim[];
}

interface ProductClaimSection {
	title: string;
	claims: readonly ProductClaim[];
}

export interface ProductContent {
	meta: PageMeta;
	eyebrow: string;
	headline: string;
	currentScope: string;
	heroClaims: readonly ProductClaim[];
	heroClaimSeparator: string;
	activitiesLabel: string;
	activitiesTitle: string;
	boundaryLabel: string;
	contextLabel: string;
	workspaceBoundary: {
		title: string;
		customer: ProductClaimSection;
		yonaris: ProductClaimSection;
	};
	coverage: ProductClaimSection;
	workbench: {
		eyebrow: string;
		title: string;
		description: string;
		ui: ProductWorkbenchUi;
		views: readonly ProductWorkbenchView[];
	};
	contextLinks: {
		title: string;
		geoLabel: string;
		diagnosticLabel: string;
	};
	activities: readonly ProductActivity[];
	homePreview: ProductHomePreview;
	claims: readonly ProductClaim[];
	limitations: readonly string[];
}

